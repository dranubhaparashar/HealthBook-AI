"""Write the public deployment files for a given Render API origin and Firebase project.

    python scripts/configure_deployment.py --api-origin https://your-api.onrender.com --firebase-project my-project-id

Writes: web/config.js, firebase.json, .firebaserc (all public values, safe to commit) and
deploy/supabase/setup.generated.sql (contains the scheduler key, git-ignored) when BABYCARE_SCHEDULER_KEY or
--scheduler-key is given. Nothing here contacts any service.
"""
import argparse
import json
import os
import re
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parent.parent


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--api-origin', required=True, help='Render service URL, e.g. https://your-api.onrender.com')
    ap.add_argument('--firebase-project', required=True, help='Firebase project id (Spark plan)')
    ap.add_argument('--scheduler-key', default=os.getenv('BABYCARE_SCHEDULER_KEY', ''), help='Same value as the Render env var BABYCARE_SCHEDULER_KEY')
    args = ap.parse_args()

    origin = args.api_origin.rstrip('/')
    parsed = urlparse(origin)
    if parsed.scheme != 'https' or not parsed.netloc or parsed.path:
        raise SystemExit('--api-origin must be an https origin without a path')
    if not re.fullmatch(r'[a-z0-9][a-z0-9-]{3,40}', args.firebase_project):
        raise SystemExit('--firebase-project must look like a Firebase project id')

    hosted = [f'{args.firebase_project}.web.app', f'{args.firebase_project}.firebaseapp.com']
    (ROOT / 'web' / 'config.js').write_text(
        '// Generated by scripts/configure_deployment.py (public values only).\n'
        '// The Render API origin applies only on the Firebase Hosting domains; a local server keeps same-origin /api.\n'
        f'window.BABYCARE_CONFIG={json.dumps(hosted)}.includes(location.hostname)?{{apiBase:{json.dumps(origin)}}}:{{}};\n', encoding='utf-8')
    template = (ROOT / 'deploy' / 'firebase.template.json').read_text(encoding='utf-8').replace('__API_ORIGIN__', origin)
    (ROOT / 'firebase.json').write_text(template, encoding='utf-8')
    (ROOT / '.firebaserc').write_text(json.dumps({'projects': {'default': args.firebase_project}}, indent=2) + '\n', encoding='utf-8')
    written = ['web/config.js', 'firebase.json', '.firebaserc']

    if args.scheduler_key:
        if len(args.scheduler_key) < 24:
            raise SystemExit('Scheduler key must be at least 24 characters')
        sql = (ROOT / 'deploy' / 'supabase' / 'setup.sql').read_text(encoding='utf-8')
        sql = sql.replace('__API_ORIGIN__', origin).replace('__SCHEDULER_KEY__', args.scheduler_key.replace("'", "''"))
        target = ROOT / 'deploy' / 'supabase' / 'setup.generated.sql'
        target.write_text(sql, encoding='utf-8')
        written.append('deploy/supabase/setup.generated.sql (git-ignored, contains the scheduler key)')
    else:
        written.append('(skipped setup.generated.sql: pass --scheduler-key or set BABYCARE_SCHEDULER_KEY)')

    print('Wrote:')
    for item in written:
        print('  -', item)
    print('\nNext: npx firebase-tools deploy --only hosting   (site)  |  paste setup.generated.sql into the Supabase SQL editor (scheduler)')


if __name__ == '__main__':
    main()
